// Command gen writes the exported method set of every distribution from the
// //stats:continuous and //stats:discrete directives in the package's
// source files:
//
//	//stats:continuous Beta beta a=A b=B
//	//stats:discrete Binomial binom n=N:int p=P
//
// declares that the struct Beta (fields A, B, Loc, Scale) is
// scipy.stats.beta with shape arguments a and b, and that its standard form
// is returned by a hand-written method std(). Each directive produces
// zz_<name>.go with the constructor, Validate, and the methods of
// Continuous or Discrete, which apply loc, scale and the boundary rules
// before calling the standard form.
//
// Run from the module root:
//
//	go run internal/gen/main.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"text/template"
)

type param struct {
	Arg, Field, Type string
}

type dist struct {
	Kind, Name, SciPy string
	Params            []param
	File              string
	HasFit            bool
}

func (d dist) Lower() string { return strings.ToLower(d.Name) }

// Args is the constructor's argument list: "a, b, loc, scale float64".
func (d dist) Args() string {
	var parts []string
	for _, p := range d.Params {
		parts = append(parts, p.Arg+" "+p.Type)
	}
	if d.Kind == "continuous" {
		parts = append(parts, "loc, scale float64")
	} else {
		parts = append(parts, "loc float64")
	}
	return strings.Join(parts, ", ")
}

// Lit is the struct literal: "Beta{A: a, B: b, Loc: loc, Scale: scale}".
func (d dist) Lit() string {
	var parts []string
	for _, p := range d.Params {
		parts = append(parts, p.Field+": "+p.Arg)
	}
	parts = append(parts, "Loc: loc")
	if d.Kind == "continuous" {
		parts = append(parts, "Scale: scale")
	}
	return d.Name + "{" + strings.Join(parts, ", ") + "}"
}

// SciArgs is SciPy's argument list after x: "a, b, loc, scale".
func (d dist) SciArgs() string {
	var parts []string
	for _, p := range d.Params {
		parts = append(parts, p.Arg)
	}
	parts = append(parts, "loc")
	if d.Kind == "continuous" {
		parts = append(parts, "scale")
	}
	return strings.Join(parts, ", ")
}

// Fmt is the format and the fields for Validate's message.
func (d dist) Fmt() string {
	var parts []string
	for _, p := range d.Params {
		parts = append(parts, p.Arg+"=%v")
	}
	return strings.Join(parts, " ")
}

func (d dist) FmtArgs() string {
	var parts []string
	for _, p := range d.Params {
		parts = append(parts, "d."+p.Field)
	}
	return strings.Join(parts, ", ")
}

var directive = regexp.MustCompile(`(?m)^//stats:(continuous|discrete) (\w+) (\w+)((?: \w+=\w+(?::\w+)?)*)\s*$`)

func main() {
	files, err := filepath.Glob("*.go")
	if err != nil {
		log.Fatal(err)
	}
	sort.Strings(files)
	var ds []dist
	for _, f := range files {
		if strings.HasPrefix(f, "zz_") || strings.HasSuffix(f, "_test.go") {
			continue
		}
		src, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		for _, m := range directive.FindAllStringSubmatch(string(src), -1) {
			d := dist{Kind: m[1], Name: m[2], SciPy: m[3], File: f}
			for _, kv := range strings.Fields(m[4]) {
				arg, rest, _ := strings.Cut(kv, "=")
				field, typ, ok := strings.Cut(rest, ":")
				if !ok {
					typ = "float64"
				}
				d.Params = append(d.Params, param{arg, field, typ})
			}
			d.HasFit = strings.Contains(string(src), "func Fit"+d.Name+"[")
			ds = append(ds, d)
		}
	}
	old, _ := filepath.Glob("zz_dist_*.go") // includes the _test.go files
	for _, f := range old {
		os.Remove(f)
	}
	for _, d := range ds {
		var b bytes.Buffer
		t := contTmpl
		if d.Kind == "discrete" {
			t = discTmpl
		}
		if err := t.Execute(&b, d); err != nil {
			log.Fatal(err)
		}
		out, err := format.Source(b.Bytes())
		if err != nil {
			log.Fatalf("%s: %v\n%s", d.Name, err, b.Bytes())
		}
		name := "zz_dist_" + d.Lower() + ".go"
		if err := os.WriteFile(name, out, 0o644); err != nil {
			log.Fatal(err)
		}
		b.Reset()
		if err := testTmpl.Execute(&b, d); err != nil {
			log.Fatal(err)
		}
		out, err = format.Source(b.Bytes())
		if err != nil {
			log.Fatalf("%s: %v\n%s", d.Name, err, b.Bytes())
		}
		tname := "zz_dist_" + d.Lower() + "_test.go"
		if err := os.WriteFile(tname, out, 0o644); err != nil {
			log.Fatal(err)
		}
		fmt.Println(name, tname)
	}
}

