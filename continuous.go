// Continuous is the method set every continuous distribution of this
// package has: the methods of a frozen scipy.stats.rv_continuous
// (scipy.stats.norm(loc, scale).pdf(x) is Normal{Loc: loc, Scale:
// scale}.PDF(x)).
//
// Every distribution is a struct of its shape parameters plus Loc and
// Scale, with SciPy's meaning: if Y has the standard distribution (Loc 0,
// Scale 1), X = Loc + Scale·Y. Scale must be positive: the zero value of a
// distribution struct is not a valid distribution, and its methods return
// NaN, as SciPy does for out-of-domain parameters. The NewXxx constructors
// return an error instead, and Validate says what is wrong.
//
// The methods are pure functions of the receiver, safe for concurrent use.
// To apply one to an array, use ndarray's Map: x.Map(d.CDF).
type Continuous interface {
	// PDF is the probability density at x (scipy pdf).
	PDF(x float64) float64
	// LogPDF is log PDF(x), accurate where PDF underflows (scipy logpdf).
	LogPDF(x float64) float64
	// CDF is P(X <= x) (scipy cdf).
	CDF(x float64) float64
	// LogCDF is log CDF(x), accurate where CDF underflows (scipy logcdf).
	LogCDF(x float64) float64
	// SF is the survival function P(X > x) = 1 - CDF(x), computed without
	// the cancellation (scipy sf).
	SF(x float64) float64
	// LogSF is log SF(x) (scipy logsf).
	LogSF(x float64) float64
	// PPF is the quantile function, the inverse of CDF (scipy ppf).
	PPF(p float64) float64
	// ISF is the inverse of SF: ISF(q) = PPF(1-q) without the rounding of
	// 1-q (scipy isf).
	ISF(q float64) float64
	// Mean, Var, Std, Skew and Kurtosis (excess, Fisher's definition) are
	// the moments SciPy's stats(moments="mvsk") returns; ±Inf or NaN where
	// they do not exist, as in SciPy.
	Mean() float64
	Var() float64
	Std() float64
	Skew() float64
	Kurtosis() float64
	// Median is PPF(0.5), in closed form where there is one.
	Median() float64
	// Entropy is the differential entropy in nats (scipy entropy).
	Entropy() float64
	// Moment is the non-central moment E[X^n] (scipy moment(n)).
	Moment(n int) float64
	// Interval is the equal-tailed interval holding the given probability
	// mass: (PPF((1-c)/2), PPF((1+c)/2)) (scipy interval(confidence)).
	Interval(confidence float64) (lo, hi float64)
	// Support is the closed interval outside which the density is zero
	// (scipy support()).
	Support() (lo, hi float64)
	// Rvs draws random variates with the shape given by size (no size: a
	// 0-d array), consuming g exactly as scipy rvs(size=size,
	// random_state=g) consumes a numpy.random.Generator; see the package
	// documentation for which distributions reproduce SciPy's draws bit
	// for bit.
	Rvs(g *random.Generator, size ...int) (*ndarray.Array, error)
	// Validate returns an error wrapping ErrParam when a parameter is out
	// of the distribution's domain.
	Validate() error
}

// contStd is a continuous distribution in standard form (loc 0, scale 1)
// with its shape parameters bound. The exported methods of each
// distribution (generated by internal/gen from a //stats:continuous
// directive) apply loc and scale and the boundary rules below, so that the
// standard form only has to be right where it is called:
//
//   - pdf and logpdf: z finite and in the closed support [a, b];
//   - cdf, sf, logcdf, logsf: z in the open support (a, b);
//   - ppf and isf: p in the open interval (0, 1);
//   - every method: only when valid() is true.
type contStd interface {
	valid() bool
	support() (a, b float64)
	pdf(z float64) float64
	logpdf(z float64) float64
	cdf(z float64) float64
	logcdf(z float64) float64
	sf(z float64) float64
	logsf(z float64) float64
	ppf(p float64) float64
	isf(q float64) float64
	mean() float64
	variance() float64
	skew() float64
	kurtosis() float64
	median() float64
	entropy() float64
	// munp is the raw moment E[Y^n] of the standard form, n >= 1.
	munp(n int) float64
	// rvs draws standard variates exactly as SciPy's _rvs does.
	rvs(g *random.Generator, size []int) (*ndarray.Array, error)
}

// momentLocScale is E[(loc + scale·Y)^n] from the raw moments of Y, the
// expansion SciPy's rv_continuous.moment uses:
// loc^n · Σ C(n,k) (scale/loc)^k E[Y^k], or scale^n·E[Y^n] when loc is 0.
// raw(k) is E[Y^k] (rawMoment).
func momentLocScale(n int, loc, scale float64, raw func(int) float64) float64 {
	switch {
	case n < 0:
		return math.NaN()
	case n == 0:
		return 1
	case loc == 0:
		return math.Pow(scale, float64(n)) * raw(n)
	}
	fac := scale / loc
	res := 1.0 // k = 0: C(n,0)·fac^0·E[Y^0]
	c := 1.0
	for k := 1; k <= n; k++ {
		c = c * float64(n-k+1) / float64(k)
		res += c * math.Pow(fac, float64(k)) * raw(k)
	}
	return res * math.Pow(loc, float64(n))
}

// stdMoments is what rawMoment needs of a standard form.
type stdMoments interface {
	mean() float64
	variance() float64
	skew() float64
	kurtosis() float64
	munp(n int) float64
}

// rawMoment is E[Y^n] for n >= 1: munp(n) when it is finite, and otherwise,
// for n <= 4, the value SciPy's _moment_from_stats derives from the mean,
// variance, skewness and kurtosis, so that a moment that does not exist is
// +Inf or NaN exactly where SciPy says so.
func rawMoment(s stdMoments, n int) float64 {
	v := s.munp(n)
	if finite(v) || n > 4 {
		return v
	}
	mu, mu2 := s.mean(), s.variance()
	switch n {
	case 1:
		return mu
	case 2:
		return mu2 + mu*mu
	case 3:
		mu3 := s.skew() * math.Pow(mu2, 1.5)
		return mu3 + 3*mu*mu2 + mu*mu*mu
	}
	mu4 := (s.kurtosis() + 3) * (mu2 * mu2)
	mu3 := s.skew() * math.Pow(mu2, 1.5)
	return mu4 + 4*mu*mu3 + 6*mu*mu*mu2 + mu*mu*mu*mu
}

// locScaleDraws applies X = Y·scale + loc to fresh draws in place, in
// SciPy's order (vals * scale + loc, the product rounded first).
func locScaleDraws(a *ndarray.Array, loc, scale float64) *ndarray.Array {
	v, _ := ndarray.Data[float64](a)
	for i, y := range v {
		v[i] = float64(y*scale) + loc
	}
	return a
}

// finite reports whether x is neither NaN nor ±Inf.
func finite(x float64) bool { return !math.IsNaN(x) && !math.IsInf(x, 0) }
